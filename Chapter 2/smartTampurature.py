#take input in Calsius and print its equivalent in Fahrenheit and Kelvin
#Formula - Fahrenheit = (C * 9/5) + 32
#Formula - Kelvin = C + 273.15

calcius = int(input("Enter the value of calcius - "))

farhenheit = (calcius * (9/5)) + 32
kelvin = calcius + 273.15

print("Calcius to fahrenheit = ", farhenheit)
print("Calcius to kelvin = ", kelvin)

